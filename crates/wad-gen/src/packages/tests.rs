#[test]
fn closure_adds_what_packages_need_in_order() {
    assert_eq!(
        closure(&["ext-rust-lang.rust-analyzer", "rust", "rpm-krita"]),
        s(&["cpp", "rust", "vscode", "rpm-krita", "ext-rust-lang.rust-analyzer"])
    );
    assert_eq!(closure(&["ext-b.b", "ext-a.a"]), s(&["vscode", "ext-a.a", "ext-b.b"]));
    assert_eq!(closure(&["python", "python"]), s(&["python"]));
    assert_eq!(closure::<&str>(&[]), Vec::<String>::new());
    assert_eq!(needs("ext-anthropic.claude-code"), ["vscode"]);
    assert_eq!(needs("rust"), ["cpp"]);
    assert!(needs("rpm-krita").is_empty());
}

#[test]
fn stack_order_builds_on_what_the_machine_stores() {
    let iq = s(&["cpp", "vscode", "rpm-krita", "ext-ms-vscode.cpptools"]);
    // Rust added: the whole chain stored, then the new ones.
    let mut want = iq.clone();
    want.extend(s(&["rust", "ext-rust-lang.rust-analyzer"]));
    assert_eq!(
        stack_order(&closure(&want), std::slice::from_ref(&iq)),
        s(&["cpp", "vscode", "rpm-krita", "ext-ms-vscode.cpptools", "rust", "ext-rust-lang.rust-analyzer"])
    );
    // Krita taken out: the chain up to it, then the rest.
    let want = closure(&["cpp", "vscode", "ext-ms-vscode.cpptools"]);
    assert_eq!(stack_order(&want, std::slice::from_ref(&iq)), s(&["cpp", "vscode", "ext-ms-vscode.cpptools"]));
    // Nothing stored: WadOS's order.
    assert_eq!(stack_order(&want, &[]), want);
    // The longest of several.
    assert_eq!(
        stack_order(&s(&["rpm-krita", "vscode", "cpp"]), &[s(&["cpp"]), iq])[..3],
        s(&["cpp", "vscode", "rpm-krita"])
    );
}

#[test]
fn a_package_containerfile_captures_on_its_needs() {
    let f = package_containerfile(
        "ext-rust-lang.rust-analyzer",
        "localhost/wados-base:44",
        &[("vscode".into(), "localhost/wados-pkg-vscode:52e5f2a601a8".into())],
        true,
    )
    .expect("a Containerfile");
    let want = [
        "# The ext-rust-lang.rust-analyzer package: what the VS Code extension rust-lang.rust-analyzer adds to the base. Generated by wad-gen.",
        "ARG BASE_IMAGE=localhost/wados-base:44",
        "FROM ${BASE_IMAGE} AS build",
        "COPY --from=localhost/wados-pkg-vscode:52e5f2a601a8 / /",
        "RUN wadspaces-pkg assemble",
        // A token at hand, but an extension's build doesn't ask GitHub: it doesn't get it.
        r#"RUN ["wadspaces-pkg","capture","ext-rust-lang.rust-analyzer","--out","/out","--needs","vscode","--probe","python3 -c 'import json; print(json.load(open(\"/usr/share/wadspaces/vscode-extensions.d/rust-lang.rust-analyzer.json\"))[\"version\"])'","--","wadspaces-vscode-extensions","rust-lang.rust-analyzer"]"#,
        "",
        "FROM scratch",
        "COPY --from=build /out/ /",
        r#"LABEL io.wadspaces.pkg="ext-rust-lang.rust-analyzer" io.wadspaces.pkg.needs="vscode""#,
    ];
    assert_eq!(f, want.join("\n") + "\n");

    // An app's RPMs: wadspaces-dnf (wadspaces-apt's command line), rpm's version.
    let rpm = package_containerfile("rpm-krita", "b", &[], true).expect("a Containerfile");
    assert!(rpm.starts_with("# The rpm-krita package: what krita from Fedora adds to the base."), "{rpm}");
    assert!(
        rpm.contains(r#"RUN ["wadspaces-pkg","capture","rpm-krita","--out","/out","--probe","rpm -q --qf '%{VERSION}-%{RELEASE}' krita","--","sh","-c","wadspaces-dnf krita --desktop org.kde.krita.desktop krita && wadspaces-dnf --clean"]"#),
        "{rpm}"
    );
    assert!(!rpm.contains("assemble"), "no needs, nothing to put together: {rpm}");
    assert!(rpm.ends_with("LABEL io.wadspaces.pkg=\"rpm-krita\" io.wadspaces.pkg.needs=\"\"\n"), "{rpm}");

    // A feature: wadspaces-feature, on what it needs.
    let rust = package_containerfile("rust", "b", &[("cpp".into(), "c".into())], false).expect("a Containerfile");
    assert!(
        rust.contains(r#"RUN ["wadspaces-pkg","capture","rust","--out","/out","--needs","cpp","--probe","rustc --version","--","wadspaces-feature","rust"]"#),
        "{rust}"
    );

    assert_eq!(
        package_containerfile("rust", "b", &[], false),
        Err(Error::Needs { id: "rust".into(), missing: "cpp".into() })
    );
    assert_eq!(
        package_containerfile("ext-a.b", "b", &[], false),
        Err(Error::Needs { id: "ext-a.b".into(), missing: "vscode".into() })
    );
    assert_eq!(package_containerfile("rpm-obsidian", "b", &[], false), Err(Error::Unknown("rpm-obsidian".into())));
}

#[test]
fn only_a_build_that_asks_githubs_api_gets_the_token() {
    let mount = "--mount=type=secret,id=github_token";
    for id in all() {
        let needs: Vec<(String, String)> = closure(&self::needs(&id)).into_iter().map(|n| (n, "r".into())).collect();
        let f = package_containerfile(&id, "b", &needs, true).expect("a Containerfile");
        assert_eq!(f.contains(mount), uses_github(&id), "{id}");
    }
    // A script that asks GitHub (an AppImage's), with the token at hand.
    static APPIMAGE: Feature = Feature { name: "obsidian", needs: &[], desktop: None, probe: None, github: true };
    let f = capture_file("obsidian", &Source::Feature(&APPIMAGE), "b", &[], true);
    assert!(
        f.contains(&format!("RUN {mount} [\"wadspaces-pkg\",\"capture\",\"obsidian\",\"--out\",\"/out\",\"--\"")),
        "{f}"
    );
}

#[test]
fn chains_and_their_labels() {
    let pkgs = vec![
        ("cpp".to_string(), local_ref("cpp", "sha256:41fc6e02a4d9aaaa")),
        ("rust".to_string(), local_ref("rust", "448760a5be45bbbb")),
    ];
    assert_eq!(pkgs[0].1, "localhost/wados-pkg-cpp:41fc6e02a4d9");
    // The same packages on the same base: the same chain.
    let c = chain_ref("sha256:base1", &pkgs);
    assert!(c.starts_with("localhost/wados-chain:") && c.len() == CHAIN.len() + 13, "{c}");
    assert_eq!(c, chain_ref("base1", &pkgs));
    assert_ne!(c, chain_ref("base2", &pkgs), "another base");
    assert_ne!(c, chain_ref("base1", &pkgs[..1]), "a shorter chain");
    let reversed: Vec<_> = pkgs.iter().rev().cloned().collect();
    assert_ne!(c, chain_ref("base1", &reversed), "another order");
    assert_eq!(
        chain_step("localhost/wados-chain:aaaaaaaaaaaa", "sha256:a1", &pkgs[1].1, &pkgs),
        "# A chain image. Generated by wad-gen.\nFROM localhost/wados-chain:aaaaaaaaaaaa\n\
         COPY --from=localhost/wados-pkg-rust:448760a5be45 / /\n\
         LABEL io.wadspaces.chain=\"cpp@41fc6e02a4d9,rust@448760a5be45\" io.wadspaces.from=\"sha256:a1\"\n"
    );
    assert_eq!(pkgs_label(&pkgs), "cpp@41fc6e02a4d9,rust@448760a5be45");
    assert_eq!(pkgs_of_label(&pkgs_label(&pkgs)), s(&["cpp", "rust"]));
    assert_eq!(pkgs_of_label(""), Vec::<String>::new());
    assert_eq!(remote_ref("vscode", "f44.1"), "ghcr.io/hunggod/wados-pkg-vscode:f44.1");
    assert_eq!(meta_path("rust"), "/usr/share/wadspaces/pkg/rust/meta.json");
}

#[test]
fn ci_builds_the_catalog_in_waves() {
    let all = all();
    assert_eq!(
        all,
        s(&[
            "cpp",
            "python",
            "nodejs",
            "rust",
            "vscode",
            "rpm-krita",
            "ext-anthropic.claude-code",
            "ext-dbaeumer.vscode-eslint",
            "ext-eamodio.gitlens",
            "ext-esbenp.prettier-vscode",
            "ext-ms-python.python",
            "ext-ms-vscode.cpptools",
            "ext-rust-lang.rust-analyzer",
        ])
    );
    let waves = waves(&all);
    let wave_of = |id: &str| waves.iter().position(|w| w.iter().any(|x| x == id));
    assert_eq!(wave_of("cpp"), Some(0));
    assert_eq!(wave_of("vscode"), Some(0));
    assert_eq!(wave_of("rpm-krita"), Some(0));
    assert_eq!(wave_of("rust"), Some(1));
    assert_eq!(wave_of("ext-anthropic.claude-code"), Some(1));
    assert_eq!(waves.len(), 2);
    assert_eq!(waves.iter().map(Vec::len).sum::<usize>(), all.len());
    // Asked for by id, what it needs comes too.
    assert_eq!(super::waves(&["rust", "python"]), [s(&["cpp", "python"]), s(&["rust"])]);
}
