use super::*;

fn s(v: &[&str]) -> Vec<String> {
    v.iter().map(|x| x.to_string()).collect()
}

#[test]
fn package_ids() {
    assert_eq!(of_app(AppId::Vscode).as_deref(), Some("vscode"));
    assert_eq!(of_app(AppId::Krita).as_deref(), Some("rpm-krita"));
    assert_eq!(of_app(AppId::Wadbrowser), None, "the base has it");
    assert_eq!(of_app(AppId::Terminal), None, "the base has it");
    assert_eq!(of_app(AppId::Obsidian), None, "not packaged yet");
    assert_eq!(of_tool("rust").as_deref(), Some("rust"));
    assert_eq!(of_tool("go"), None, "retired from the catalog");
    assert_eq!(of_tool("firebase"), None, "not packaged yet");
    assert_eq!(of_tool("rm -rf"), None);
    assert_eq!(of_extension("Rust-Lang.rust-analyzer").as_deref(), Some("ext-rust-lang.rust-analyzer"));
    assert_eq!(of_extension("bad id; rm"), None);
    assert!(matches!(source("vscode"), Some(Source::Feature(f)) if f.name == "vscode"));
    assert!(matches!(source("rpm-krita"), Some(Source::Rpm { app: AppId::Krita, rpm }) if rpm.packages == ["krita"]));
    assert_eq!(source("rpm-vscode"), None, "VS Code isn't Fedora's");
    assert_eq!(source("rpm-nope"), None);
    assert_eq!(source("apt-lmms"), None, "v1's");
    assert_eq!(source("ext-vadimcn.vscode-lldb"), Some(Source::Extension("vadimcn.vscode-lldb".into())));
    assert_eq!(source("whatever"), None);
}

