#!/usr/bin/env bash
# Writes images/stream/requirements.txt: Selkies (SELKIES, below) and
# everything it needs, as the binary wheels Fedora 44's Python takes, each
# pinned by version and sha256. The Containerfile installs exactly those
# (pip --require-hashes --no-deps --only-binary=:all:), so a build never
# resolves anything itself.
#
#   images/stream/lock.sh             after changing SELKIES (or to take the
#                                     newest of Selkies' unpinned needs)
#
# pip runs in a throwaway container of the stream image's own base (its
# Python, its platform), downloading wheels only: nothing downloaded is
# built or run. pip checks each wheel against the sha256 PyPI's index gives
# for it; the hashes written are of those files. Read the diff before
# committing it.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
# Selkies' release. Its wheel brings its web client (selkies/selkies_web,
# built from the same tag) and pins pixelflux and pcmflux exactly.
SELKIES=2.2.1
FROM="$(sed -n 's/^FROM \(ghcr.io\/linuxserver\/baseimage-fedora:44@sha256:[0-9a-f]*\).*/\1/p' "${HERE}/Containerfile")"
[[ -n "${FROM}" ]] || { echo "no FROM in ${HERE}/Containerfile" >&2; exit 1; }

out="$(mktemp -d)"
trap 'rm -rf "${out}"' EXIT
podman run --rm --entrypoint '' --security-opt label=disable -v "${out}":/out "${FROM}" bash -c '
    set -euo pipefail
    dnf -y -q --setopt=install_weak_deps=False install python3 python3-pip > /dev/null 2>&1
    python3 -I -m pip download -q --disable-pip-version-check --no-cache-dir \
        --only-binary=:all: -d /tmp/wheels "selkies=='"${SELKIES}"'"
    cd /tmp/wheels
    python3 -I - <<"PY" > /out/requirements.txt
import hashlib, pathlib, re, sys
lines = []
for p in sorted(pathlib.Path(".").glob("*.whl"), key=lambda p: p.name.lower()):
    name, version = p.name.split("-")[:2]
    name = re.sub(r"[-_.]+", "-", name).lower()
    digest = hashlib.sha256(p.read_bytes()).hexdigest()
    lines.append(f"{name}=={version} \\\n    --hash=sha256:{digest}")
print("\n".join(lines))
PY
    python3 --version > /out/python
'
{
    echo "# Generated by images/stream/lock.sh: Selkies ${SELKIES} and what it needs, as"
    echo "# wheels for $(cat "${out}/python") on Fedora 44 (x86_64), pinned by sha256."
    echo "# Do not edit by hand."
    cat "${out}/requirements.txt"
} > "${HERE}/requirements.txt"
echo "wrote ${HERE}/requirements.txt ($(grep -c '==' "${HERE}/requirements.txt") wheels)"
